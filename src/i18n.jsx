export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return window.localStorage.getItem(storageKey) === 'ar' ? 'ar' : 'en'
    } catch {
      return 'en'
    }
  })

  useEffect(() => {
    const isArabic = language === 'ar'
    document.documentElement.lang = language
    document.documentElement.dir = isArabic ? 'rtl' : 'ltr'
    document.title = isArabic ? 'ساينس لإدارة الفعاليات' : 'SCIENCE EVENT MANAGEMENT'
    const description = document.querySelector('meta[name="description"]')
    if (description) {
      description.content = isArabic
        ? 'ساينس لإدارة الفعاليات تنظم المؤتمرات الطبية والأيام العلمية وفعاليات الشركات والمعارض.'
        : 'SCIENCE EVENT MANAGEMENT creates premium event experiences, event production, branding, and digital event solutions.'
    }

    try {
      window.localStorage.setItem(storageKey, language)
    } catch {
      // Keep the selected language for the current session.
    }
  }, [language])

  const t = (text) => (language === 'ar' ? arabicTranslations[text] ?? text : text)

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}